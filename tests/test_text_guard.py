#!/usr/bin/env python3
"""Защита от обрубленных постов.

Реальный случай: у клиента в канал ушёл пост, оборванный на фразе
«Я часто замечаю, как меняется настроение человека» — без точки, а следом
приклеился призыв к действию. Причина: обрезка по последнему законченному
предложению срабатывала только при finish_reason=length, а модель вернула
finish_reason=stop. Здесь проверяется, что такой текст больше не пройдёт.

Сеть не нужна: проверяются чистые функции над строками.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from helpers import Checks, load_module  # noqa: E402

cp, http = load_module("clients_post")
c = Checks("защита от обрубленных постов")


def eq(name, got, want):
    c.ok(name, got == want, got)


# ---------- законченность текста ----------

eq("пост с точкой закончен", cp.text_is_complete("Всё готово."), True)
eq("вопрос тоже конец", cp.text_is_complete("А вы проверили выписку?"), True)
eq("восклицание тоже конец", cp.text_is_complete("С праздником!"), True)
eq("многоточие тоже конец", cp.text_is_complete("Иногда стоит подождать…"), True)
eq("эмодзи после точки не мешает", cp.text_is_complete("С Днём знаний! 🎉"), True)
eq("кавычка после точки не мешает", cp.text_is_complete("Он сказал: «готово»."), True)

eq("обрыв на полуслове пойман", cp.text_is_complete("меняется настроение человека"), False)
eq("обрыв на запятой пойман", cp.text_is_complete("дом становится союзником,"), False)
eq("обрыв на тире пойман", cp.text_is_complete("а дальше начинается —"), False)
# пустая строка входит в любую строку — без явной проверки пустой ответ
# модели считался бы законченным постом
eq("пустой текст не закончен", cp.text_is_complete("   "), False)
eq("None не закончен", cp.text_is_complete(None), False)


# ---------- тот самый пост ----------

BROKEN = (
    "Планировочное решение — это не просто линии на чертеже, а готовый "
    "сценарий того, как будет протекать мое утро или спокойный вечер. "
    "Когда в квартире правильный свет мягко падает на обеденную зону, "
    "а путь из спальни на кухню не преграждают лишние углы, дом становится "
    "настоящим союзником.\n\n"
    "Я часто замечаю, как меняется настроение человека"
)

c.ok("реальный обрубок распознан", not cp.text_is_complete(BROKEN))
c.ok("обрубок длиннее 40 слов, но всё равно забракован",
     len(BROKEN.split()) > 40 and not cp.rubric_output_ok("observation", BROKEN))

FIXED = cp.trim_to_sentence(BROKEN)
c.ok("после обрезки текст закончен", cp.text_is_complete(FIXED))
c.ok("обрезка убрала только битый хвост", FIXED.endswith("настоящим союзником."))
c.ok("обрезанный текст остаётся публикуемым", cp.rubric_output_ok("observation", FIXED))


# ---------- обрезка не трогает целое ----------

GOOD = "Первая мысль доведена до конца. И вторая тоже закончена."
eq("законченный текст обрезка не трогает", cp.trim_to_sentence(GOOD), GOOD)
eq("пустую строку обрезка не ломает", cp.trim_to_sentence("   "), "")


# ---------- служебные пометки модели ----------

NOISY = (
    "Готовый пост про планировку. Вторая мысль доведена до конца.\n\n"
    "Я часто замечаю, как меняется настроение человека\n"
    "Word count check: 118 words\n"
)
cleaned = cp.strip_model_noise(NOISY)
c.ok("пометка модели убрана", "Word count check" not in cleaned)
c.ok("вместе с пометкой ушёл и обрубок над ней",
     cp.text_is_complete(cp.trim_to_sentence(cleaned)))

FENCED = "```\nПост в обёртке. Всё на месте.\n```"
eq("обёртка ``` снята", cp.strip_model_noise(FENCED), "Пост в обёртке. Всё на месте.")

# текст без пометок не должен пострадать
PLAIN = "Обычный пост. Без всяких пометок."
eq("чистый текст не тронут", cp.strip_model_noise(PLAIN), PLAIN)


sys.exit(c.finish())
